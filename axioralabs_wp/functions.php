function wb_reading_time(){
  global $post;
  if(!$post) return '1 min read';
  $words = str_word_count(strip_tags($post->post_content));
  $minutes = ceil($words / 200);
  return '~' . ($minutes > 0 ? $minutes : 1) . ' min read';
}

/* Featured image, or a branded gradient panel when a post has none.
   Keeps the card grid even instead of collapsing on a missing image. */
function wb_post_thumb($size='medium_large'){
  if(has_post_thumbnail()){
    the_post_thumbnail($size,array('loading'=>'lazy','alt'=>esc_attr(get_the_title())));
    return;
  }
  echo '<span class="post-thumb-fallback"><svg class="icon" aria-hidden="true"><use href="#i-spark"/></svg></span>';
}

/* Excerpt trimmed to a word count. Uses the hand-written excerpt when there is
   one, otherwise falls back to the post body. */
function wb_excerpt($words=24){
  $text = has_excerpt() ? get_the_excerpt() : get_the_content();
  $text = strip_shortcodes($text);
  $text = wp_strip_all_tags($text);
  return wp_trim_words($text,$words,'&hellip;');
}

/* Blog page title used by home.php — the title of the page assigned as the
   "Posts page" under Settings → Reading, so editors control it from wp-admin. */
function wb_blog_title(){
  $id = (int) get_option('page_for_posts');
  return $id ? get_the_title($id) : 'Blog';
}
function wb_blog_intro(){
  $id = (int) get_option('page_for_posts');
  if(!$id) return '';
  $page = get_post($id);
  return $page ? wp_strip_all_tags($page->post_excerpt ? $page->post_excerpt : $page->post_content) : '';
}
