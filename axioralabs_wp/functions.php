function wb_seo_current(){
  if(!is_page()) return null;
  foreach(wb_seo_map() as $tpl=>$data){ if(is_page_template($tpl)) return $data; }
  return null;
}
add_filter('pre_get_document_title',function($title){
  $d=wb_seo_current();
  return $d ? $d[0] : $title;
});
